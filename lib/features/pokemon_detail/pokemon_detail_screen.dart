        cachedInfo?.category ??
        ref
            .watch(speciesInfoProvider(pokemon.id))
            .when(
              data: (info) => info.category,
              loading: () => '...',
              error: (_, _) => 'Unknown Pok\u00e9mon',
            ) ??
        'Unknown Pok\u00e9mon';

    final lightThemeColor = HSLColor.fromColor(themeColor)
        .withLightness(
          (HSLColor.fromColor(themeColor).lightness + 0.2).clamp(0.0, 1.0),
        )
        .toColor();

    return Scaffold(
      extendBody: true,
      backgroundColor: Colors.transparent,
      body: Container(
        decoration: BoxDecoration(
          gradient: LinearGradient(
            begin: Alignment.topCenter,
            end: Alignment.bottomCenter,
            colors: [
              themeColor,
              lightThemeColor,
              lightThemeColor,
            ],
            stops: const [0.0, 0.5, 1.0],
          ),
        ),
        child: LayoutBuilder(
          builder: (context, constraints) {
            final fullHeader = Stack(
            key: const ValueKey('full-header'),
            alignment: Alignment.topCenter,
            children: [
              Column(
                children: [
                  // 3D Image Artwork
                  Hero(
                    tag: 'pokemon-image-${pokemon.id}',
                    child: Image.asset(
                      isShiny
                          ? PokemonHelpers.getHomeShinyAssetPath(pokemon.id)
                          : PokemonHelpers.getHomeAssetPath(pokemon.id),
                      height: 300,
                      fit: BoxFit.contain,
                      cacheWidth: PokemonHelpers.cacheWidth(context, 300),
                      filterQuality: FilterQuality.medium,
                      errorBuilder: (context, error, stackTrace) => Image.asset(
                        isShiny
                            ? PokemonHelpers.getHomeAssetPath(pokemon.id)
                            : PokemonHelpers.getThumbnailAssetPath(pokemon.id),
                        height: 300,
                        fit: BoxFit.contain,
                        cacheWidth: PokemonHelpers.cacheWidth(context, 300),
                        filterQuality: FilterQuality.medium,
                        errorBuilder: (context, error, stackTrace) =>
                            Image.asset(
                              PokemonHelpers.getThumbnailAssetPath(pokemon.id),
